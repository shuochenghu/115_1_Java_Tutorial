// 類別：MissionLogCheck（教師驗證工具）
// 意義：用 15 個固定案例確認 MissionLog 的完整輸出正確。
// 作用：沿用第 4 週的 15 個案例（輸出文字改為中文），確認程式結構改變後，行為和輸出都沒有變。
